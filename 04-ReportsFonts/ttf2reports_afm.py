#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ttf2reports_afm.py

Generate an AFM (Adobe Font Metrics) file from a TrueType font for the
Oracle Reports "screen printer" (HTML output / HTML parameter form on UNIX),
and check an existing AFM file for the specific defects that make Reports
silently reject it.

Author : Gunther Pipperr | https://pipperr.de
License: Apache 2.0

Why: The Reports screen printer (uiscreenprint.txt -> screenprinter.ppd)
resolves fonts via PPD + AFM, not via the TTF files in
REPORTS_FONT_DIRECTORY. A font that has no AFM is not available for the
HTML parameter form and falls back to *DefaultFont (Courier) or, with an
encoding mismatch, to Symbol (Greek glyphs). See
04-ReportsFonts/HTML_ParameterForm_Fonts.md for the full background.

What generation does:
- character codes 32..255 taken from the given --encoding (default cp1252 /
  WE8MSWIN1252); must match the NLS_LANG character set of the Reports
  environment, see HTML_ParameterForm_Fonts.md section 9 (Caveats)
- EncodingScheme FontSpecific (Reports passes the bytes 1:1, no charset
  matching against NLS_LANG)
- metrics scaled to 1000 units per em
- English (Windows en-US) name records for FullName / FamilyName
- CapHeight / XHeight taken from OS/2 or, for old OS/2 tables, from the
  bounding boxes of the glyphs "H" and "x"

What --check does: parses an existing AFM file (plain text, no fontTools
needed) and flags the defects known to make Reports reject it or silently
fall back to *DefaultFont: CapHeight/XHeight of 0, EncodingScheme other
than FontSpecific, a FontName that does not match the AFM file's own name,
and (best-effort only) a non-ASCII FullName.

Requires: python3-fonttools (OL9 AppStream) or "pip install --user fonttools"
          -- only for generation; --check has no extra dependency.

Usage:
    python3 ttf2reports_afm.py <font.ttf> <AFM-Name> [--encoding ENC] [-o FILE]
    python3 ttf2reports_afm.py --check <afm-file>

Examples:
    python3 ttf2reports_afm.py arialbd.ttf Arial-Bold > $TK_ADMIN/AFM/Arial-Bold
    python3 ttf2reports_afm.py arialbd.ttf Arial-Bold -o $TK_ADMIN/AFM/Arial-Bold
    python3 ttf2reports_afm.py --check $TK_ADMIN/AFM/Arial-Bold

The AFM-Name must be identical to the key used in the *Font line of
screenprinter.ppd and to the file name (no extension) in the AFM directory.
"""
import argparse
import os
import sys

# fontTools is only needed for AFM generation, not for --check. Import
# lazily (inside generate_afm) so --check works even without the package
# installed.


def generate_afm(src, key, encoding="cp1252"):
    """Build an AFM file (as a list of text lines) from a TrueType font.

    src      : path to the source .ttf/.ttc file
    key      : AFM/PPD font key (FontName in the output, and the expected
               file name with no extension)
    encoding : character encoding used to map codes 32..255 to glyphs; must
               match the NLS_LANG character set of the Reports environment
    """
    from fontTools.ttLib import TTFont
    from fontTools.pens.boundsPen import BoundsPen

    font = TTFont(src)

    upm = font["head"].unitsPerEm

    def s(v):
        return int(round(v * 1000.0 / upm))

    # English name records only (Windows, en-US); fallback to any record
    names = {}
    for r in font["name"].names:
        if r.platformID == 3 and r.langID == 0x409:
            names[r.nameID] = r.toUnicode()
    if not names:
        for r in font["name"].names:
            try:
                names.setdefault(r.nameID, r.toUnicode())
            except Exception:
                pass

    head = font["head"]
    post = font["post"]
    os2 = font["OS/2"]
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    gs = font.getGlyphSet()

    def bounds(glyph):
        bp = BoundsPen(gs)
        gs[glyph].draw(bp)
        return bp.bounds or (0, 0, 0, 0)

    def top(ch):
        g = cmap.get(ord(ch))
        return bounds(g)[3] if g else 0

    cap_h = getattr(os2, "sCapHeight", 0) or top("H")
    x_h = getattr(os2, "sxHeight", 0) or top("x")

    weight = "Bold" if os2.usWeightClass >= 600 else "Regular"
    full_name = names.get(4, key)
    family = names.get(1, key)
    version = names.get(5, "001.000")

    chars = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode(encoding)
        except (UnicodeDecodeError, LookupError):
            continue
        g = cmap.get(ord(ch))
        if not g:
            continue
        b = bounds(g)
        chars.append(
            "C %d ; WX %d ; N %s ; B %d %d %d %d ;"
            % (code, s(hmtx[g][0]), g, s(b[0]), s(b[1]), s(b[2]), s(b[3]))
        )

    out = [
        "StartFontMetrics 2.0",
        "Comment Generated by ttf2reports_afm.py from %s" % src.split("/")[-1],
        "FontName %s" % key,
        "FullName %s" % full_name,
        "FamilyName %s" % family,
        "Weight %s" % weight,
        "ItalicAngle %g" % post.italicAngle,
        "IsFixedPitch %s" % ("true" if post.isFixedPitch else "false"),
        "FontBBox %d %d %d %d" % (s(head.xMin), s(head.yMin), s(head.xMax), s(head.yMax)),
        "UnderlinePosition %d" % s(post.underlinePosition),
        "UnderlineThickness %d" % s(post.underlineThickness),
        "Version %s" % version,
        "EncodingScheme FontSpecific",
        "CapHeight %d" % s(cap_h),
        "XHeight %d" % s(x_h),
        "Ascender %d" % s(os2.sTypoAscender),
        "Descender %d" % s(os2.sTypoDescender),
        "StartCharMetrics %d" % len(chars),
    ]
    out.extend(chars)
    out.extend(["EndCharMetrics", "EndFontMetrics"])
    return out


def _parse_afm_fields(path):
    """Read the single-value header fields of an AFM file into a dict.

    Only the fields ttf2reports_afm.py itself writes are recognized; the
    (much larger) per-character StartCharMetrics block is ignored.
    """
    fields = {}
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith("StartCharMetrics"):
                break
            parts = line.split(None, 1)
            if len(parts) == 2:
                fields.setdefault(parts[0], parts[1])
    return fields


def check_afm(path):
    """Check an existing AFM file for the defects known to break Reports.

    Returns (ok, messages) where ok is False if anything was flagged.
    Limitation: a localized but plain-ASCII FullName (e.g. "Arial Gras"
    instead of "Arial Bold") cannot be detected automatically -- only
    non-ASCII bytes are flagged. Always eyeball the printed FullName too.
    """
    messages = []
    ok = True

    if not os.path.isfile(path):
        return False, ["file not found: %s" % path]

    fields = _parse_afm_fields(path)

    expected_name = os.path.basename(path)
    # AFM files in this workflow have no extension, but tolerate one anyway.
    for ext in (".afm", ".AFM"):
        if expected_name.endswith(ext):
            expected_name = expected_name[: -len(ext)]
            break

    font_name = fields.get("FontName", "")
    if font_name != expected_name:
        ok = False
        messages.append(
            "FontName %r does not match the AFM file name %r "
            "(PPD *Font key, AFM file name, and FontName must all be identical)"
            % (font_name, expected_name)
        )
    else:
        messages.append("FontName matches file name: %s" % font_name)

    encoding_scheme = fields.get("EncodingScheme", "")
    if encoding_scheme != "FontSpecific":
        ok = False
        messages.append(
            "EncodingScheme is %r, not FontSpecific -- Reports will charset-check "
            "this font against NLS_LANG and likely reject it" % (encoding_scheme or "(missing)")
        )
    else:
        messages.append("EncodingScheme: FontSpecific")

    for key in ("CapHeight", "XHeight"):
        raw = fields.get(key, "")
        try:
            value = int(raw)
        except ValueError:
            value = 0
        if value == 0:
            ok = False
            messages.append(
                "%s is 0 (or missing) -- this specific defect has made Reports "
                "ignore an otherwise valid AFM" % key
            )
        else:
            messages.append("%s: %s" % (key, value))

    full_name = fields.get("FullName", "")
    if full_name and any(ord(c) > 127 for c in full_name):
        ok = False
        messages.append(
            "FullName %r contains non-ASCII characters -- likely a localized "
            "name record (e.g. French \"Gras\" instead of \"Bold\"); verify by eye, "
            "this check cannot catch a localized but all-ASCII name" % full_name
        )
    else:
        messages.append(
            "FullName: %s  (eyeball this -- a localized ASCII name like "
            "\"Arial Gras\" cannot be detected automatically)" % (full_name or "(missing)")
        )

    return ok, messages


def main():
    parser = argparse.ArgumentParser(
        description="Generate (or check) an AFM file for the Oracle Reports "
        "screen printer from a TrueType font.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "font_ttf", nargs="?", metavar="<font.ttf>", help="source TrueType font file"
    )
    parser.add_argument(
        "afm_name",
        nargs="?",
        metavar="<AFM-Name>",
        help="AFM/PPD font key, e.g. Arial-Bold "
        "(must match the *Font key in screenprinter.ppd and the output file name)",
    )
    parser.add_argument(
        "--encoding",
        default="cp1252",
        metavar="ENC",
        help="character encoding for codes 32..255, default cp1252 "
        "(WE8MSWIN1252). Must match the NLS_LANG character set, e.g. "
        "iso8859-15 for WE8ISO8859P15. Not meaningful with AL32UTF8/UTF-8 "
        "NLS_LANG settings -- see HTML_ParameterForm_Fonts.md section 9.",
    )
    parser.add_argument(
        "-o",
        "--output",
        metavar="<file>",
        help="write the generated AFM to this file instead of stdout",
    )
    parser.add_argument(
        "--check",
        metavar="<afm-file>",
        help="check an existing AFM file instead of generating one; "
        "exits 1 if any defect is flagged",
    )
    args = parser.parse_args()

    if args.check:
        if args.font_ttf or args.afm_name:
            parser.error("--check cannot be combined with <font.ttf> <AFM-Name>")
        ok, messages = check_afm(args.check)
        status = "OK" if ok else "FAIL"
        sys.stdout.write("%s %s\n" % (status, args.check))
        for m in messages:
            sys.stdout.write("  - %s\n" % m)
        sys.exit(0 if ok else 1)

    if not args.font_ttf or not args.afm_name:
        parser.error(
            "both <font.ttf> and <AFM-Name> are required unless --check is given"
        )

    try:
        out = generate_afm(args.font_ttf, args.afm_name, encoding=args.encoding)
    except Exception as exc:  # noqa: BLE001 -- surface any fontTools error plainly
        sys.stderr.write("ERROR: %s\n" % exc)
        sys.exit(1)

    text = "\n".join(out) + "\n"
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
